// Deduplicate and sort strictly in alphabetical order by district name
const uniqueMap = new Map();
RAW_DATA.forEach(d => {
  const key = `${d.name} (${d.state})`;
  if (!uniqueMap.has(key)) {
    uniqueMap.set(key, d);
  }
});

const sortedDistricts = Array.from(uniqueMap.values()).sort((a, b) => 
  a.name.localeCompare(b.name, undefined, { sensitivity: 'base' })
);

console.log(`Generated ${sortedDistricts.length} unique Indian districts sorted alphabetically.`);

